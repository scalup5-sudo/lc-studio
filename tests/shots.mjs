import { chromium } from 'playwright';
import fs from 'fs';
const pv = 'preview_theme_id=195111911690';
const b = await chromium.launch();
const info = {};
const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 }, locale:'fr-FR' });
const p = await ctx.newPage();
const errs=[]; p.on('pageerror',e=>errs.push(String(e)));
await p.goto(`https://comptoir-sante-beaute.com/?${pv}`, { waitUntil: 'networkidle' }).catch(()=>{});
await p.addStyleTag({content:'#preview-bar-iframe,iframe[id*=preview]{display:none!important}'}).catch(()=>{});
const card = p.locator('#lc4-ventes .lc4-card__media').nth(1);
await card.scrollIntoViewIfNeeded(); await p.waitForTimeout(800);
const bb = await card.boundingBox();
await p.mouse.move(bb.x+bb.width*0.75, bb.y+bb.height*0.3, {steps:8}); await p.waitForTimeout(900);
await p.screenshot({ path: 'tests/shot-hover-card.png' });
const ray = p.locator('.lc4-rayons__list a').nth(2); await ray.scrollIntoViewIfNeeded(); const rb=await ray.boundingBox();
await p.mouse.move(rb.x+rb.width/2, rb.y+rb.height/2,{steps:6}); await p.waitForTimeout(900);
await p.screenshot({ path: 'tests/shot-hover-rayon.png' });
info.home = await p.evaluate(()=>({badges:document.querySelectorAll('.jdgm-prev-badge').length, stars:document.querySelectorAll('.lc4-rating .jdgm-star').length, sample:(document.querySelector('.lc4-rating')||{}).innerText}));
await p.goto(`https://comptoir-sante-beaute.com/products/couverture-lestee-7-11-15kg-grandes-dimensions?${pv}`, { waitUntil: 'networkidle' }).catch(()=>{});
await p.addStyleTag({content:'#preview-bar-iframe,iframe[id*=preview]{display:none!important}'}).catch(()=>{});
await p.waitForTimeout(2500);
await p.screenshot({ path: 'tests/shot-prod-top.png' });
const sh = p.locator('.lc4p-shot--main'); const sb = await sh.boundingBox();
await p.mouse.move(sb.x+sb.width*0.3, sb.y+sb.height*0.4,{steps:6}); await p.waitForTimeout(800);
await p.screenshot({ path: 'tests/shot-prod-zoom.png' });
await p.evaluate(()=>{const e=document.querySelector('#lc4p-avis');if(e)window.scrollTo(0,e.getBoundingClientRect().top+scrollY-100);}); await p.waitForTimeout(2500);
await p.screenshot({ path: 'tests/shot-prod-avis.png' });
info.prod = await p.evaluate(()=>({revtop:(document.querySelector('.lc4p-revtop')||{}).innerHTML?.slice(0,600), grc:(document.querySelector('.grc-product-reviews')||{}).innerHTML?.length||0, grcSummary:!!document.querySelector('.grc-product-summary'), avisHtml:(document.querySelector('#lc4p-avis')||{}).innerHTML?.slice(0,400)}));
info.errs=errs;
fs.writeFileSync('tests/info.json', JSON.stringify(info,null,1));
await b.close();
